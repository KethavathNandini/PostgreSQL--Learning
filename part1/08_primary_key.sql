DROP TABLE IF EXISTS basics.sales;
CREATE TABLE basics.sales(
    id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY ,

     title TEXT NOT NULL,
    
     price NUMERIC(10,2) NOT NULL DEFAULT 0,
     created_at TIMESTAMP DEFAULT NOW()

