/* 
PRIMARY KEY — PostgreSQL

Definition:
A Primary Key is a column or combination of columns used to uniquely identify each row in a table.

Key Points:
• Must contain unique values.
• Cannot contain NULL values.
• A table can have only one Primary Key.
• A Primary Key can contain one or multiple columns.
• Multiple columns together form a Composite Primary Key.
• It helps maintain data integrity by preventing duplicate records.

Example:
In a Students table, student_id can be a Primary Key because each student has a unique ID.

Remember:
Primary Key = UNIQUE + NOT NULL + Identifies each row
*/
